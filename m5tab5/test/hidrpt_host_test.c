#include <assert.h>
#include <stdio.h>

#include "hidrpt.h"

/* A plain boot keyboard: modifiers, a reserved byte, LEDs, six keys
 * 0x00-0x65. Nothing Apple's. */
static const uint8_t k_plain[] = {
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01,
    0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01,
    0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
    0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
    0x05, 0x08, 0x19, 0x01, 0x29, 0x05, 0x95, 0x05, 0x75, 0x01, 0x91, 0x02,
    0x95, 0x01, 0x75, 0x03, 0x91, 0x01,
    0x05, 0x07, 0x19, 0x00, 0x29, 0x65, 0x15, 0x00, 0x25, 0x65,
    0x95, 0x06, 0x75, 0x08, 0x81, 0x00,
    0xC0,
};

/* The same, with Apple's Fn bit: Usage Page 0x00FF (two bytes, as Apple
 * writes it), Usage 0x03, one bit. */
static const uint8_t k_apple_fn[] = {
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01,
    0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
    0x06, 0xFF, 0x00, 0x09, 0x03, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02,
    0x75, 0x07, 0x95, 0x01, 0x81, 0x01,
    0xC0,
};

/* A consumer collection with the globe key as a four-byte usage (its
 * page in the high half), after a vendor page. */
static const uint8_t k_globe[] = {
    0x06, 0x00, 0xFF, 0x09, 0x01, 0xA1, 0x01, 0xC0,
    0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01,
    0x0B, 0x9D, 0x02, 0x0C, 0x00, 0x75, 0x01, 0x95, 0x01, 0x81, 0x02,
    0xC0,
};

/* The globe inside a consumer usage range. */
static const uint8_t k_globe_range[] = {
    0x05, 0x0C, 0x09, 0x01, 0xA1, 0x01,
    0x1A, 0x00, 0x00, 0x2A, 0xFF, 0x03, 0x75, 0x10, 0x95, 0x01, 0x81, 0x00,
    0xC0,
};

int main(void)
{
    hidrpt_t r;

    hidrpt_scan(k_plain, sizeof k_plain, &r);
    assert(r.ok && !r.fn && !r.globe && !r.vendor && !hidrpt_apple(&r));
    assert(r.keys_max == 0xE7);

    hidrpt_scan(k_apple_fn, sizeof k_apple_fn, &r);
    assert(r.ok && r.fn && !r.globe && hidrpt_apple(&r));

    hidrpt_scan(k_globe, sizeof k_globe, &r);
    assert(r.ok && !r.fn && r.globe && r.vendor);

    hidrpt_scan(k_globe_range, sizeof k_globe_range, &r);
    assert(r.ok && r.globe);

    /* Cut off at every length: never reads past the end (ASan says so). */
    for (size_t n = 0; n < sizeof k_apple_fn; n++) hidrpt_scan(k_apple_fn, n, &r);
    const uint8_t cut[] = { 0x06, 0xFF };
    hidrpt_scan(cut, sizeof cut, &r);
    assert(!r.ok);
    const uint8_t longitem[] = { 0xFE, 0x05, 0x00, 1, 2, 3 };   /* claims 5, has 3 */
    hidrpt_scan(longitem, sizeof longitem, &r);
    assert(!r.ok);

    printf("hidrpt: ok\n");
    return 0;
}
